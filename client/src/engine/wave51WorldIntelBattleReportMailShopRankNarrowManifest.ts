export function isWave51WorldIntelBattleReportMailShopRankArtSkinOff(el: HTMLElement): boolean {
  return el.dataset.artSkin === "off" || el.closest("[data-art-skin='off']") != null;
}

export function queryClient323PanelRoot(
  doc: ParentNode,
  panelId: Client323NarrowManifestCenterPanelId,
): HTMLElement | null {
  if (doc instanceof HTMLElement && doc.dataset.centerPanel === panelId) {
    return doc;
  }
  if (panelId === "military") {
    return doc.querySelector<HTMLElement>(`.military-panel[data-center-panel="military"]`);
  }
  return doc.querySelector<HTMLElement>(`[data-center-panel="${panelId}"]`);
}

/** Safe no-op when CLIENT-316～322 sibling DOM is not mounted yet. */
export function pulseWave51ResidualNarrowHook(root: ParentNode, selector: string): void {
  const el = root.querySelector<HTMLElement>(selector);
  if (!el) return;
  el.classList.add("wave51-narrow-hook-pulse");
  window.setTimeout(() => el.classList.remove("wave51-narrow-hook-pulse"), 0);
}

export type IntelMarchPrefillResidualDeepestDeeper = {
  toX: number;
  toY: number;
  troopsSummary: string;
};

/**
 * CLIENT-322 stub: tolerates missing military form / prefill line until sibling PR lands.
 */
export function prefillMarchFormFromIntelResidualDeepestDeeper(
  doc: ParentNode,
  prefill: IntelMarchPrefillResidualDeepestDeeper,
): boolean {
  const military = queryClient323PanelRoot(doc, "military");
  if (!military) return false;
  const line =
    military.querySelector<HTMLElement>(`.${INTEL_MARCH_PREFILL_RESIDUAL_DEEPEST_DEEPER_LINE_CLASS}`) ??
    military.querySelector<HTMLElement>(
      `[data-action="${PREFILL_MARCH_FORM_FROM_INTEL_RESIDUAL_DEEPEST_DEEPER_ACTION}"]`,
    );
  if (!line) return false;
  line.textContent = `${prefill.toX},${prefill.toY} · ${prefill.troopsSummary}`;
  pulseWave51ResidualNarrowHook(military, INTEL_MARCH_PREFILL_RESIDUAL_DEEPEST_DEEPER_LINE_SELECTOR);
  return true;
}

