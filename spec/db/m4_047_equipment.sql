CREATE TABLE IF NOT EXISTS player_equipment (
    server_id      INT    NOT NULL,
    equipment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    player_id      BIGINT NOT NULL,
    cfg_id         INT    NOT NULL REFERENCES cfg_equipment(cfg_id),
    enhance_level  INT    NOT NULL DEFAULT 0 CHECK (enhance_level >= 0),
    gems           JSONB  NOT NULL DEFAULT '[]',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (server_id, equipment_id)
);
CREATE INDEX IF NOT EXISTS idx_player_equipment_owner ON player_equipment(server_id, player_id);

CREATE TABLE IF NOT EXISTS hero_equipment (
    server_id    INT    NOT NULL,
    hero_id      BIGINT NOT NULL,
    slot_type    SMALLINT NOT NULL CHECK (slot_type >= 0 AND slot_type <= 4),
    equipment_id BIGINT NOT NULL,
    PRIMARY KEY (server_id, hero_id, slot_type)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_hero_equipment_item ON hero_equipment(server_id, equipment_id);
