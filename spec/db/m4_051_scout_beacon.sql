-- R4-S2: 斥候侦察报告与烽火台敌袭预警。
CREATE TABLE IF NOT EXISTS scout_report (
    server_id   INT    NOT NULL,
    report_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    player_id   BIGINT NOT NULL,
    x           INT    NOT NULL,
    y           INT    NOT NULL,
    tier        SMALLINT NOT NULL CHECK (tier >= 1 AND tier <= 4),
    target_name VARCHAR(64) NOT NULL,
    detail      JSONB  NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (server_id, report_id)
);
CREATE INDEX IF NOT EXISTS idx_scout_report_player ON scout_report(server_id, player_id, created_at DESC);

CREATE TABLE IF NOT EXISTS beacon_warning (
    server_id         INT    NOT NULL,
    warning_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    defender_player_id BIGINT NOT NULL,
    defender_city_id  BIGINT NOT NULL,
    attacker_player_id BIGINT NOT NULL,
    x                 INT    NOT NULL,
    y                 INT    NOT NULL,
    purpose           SMALLINT NOT NULL,
    arrive_at         TIMESTAMPTZ NOT NULL,
    beacon_level      SMALLINT NOT NULL,
    attacker_troops   INT    NOT NULL DEFAULT 0,
    hero_id           BIGINT NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (server_id, warning_id)
);
CREATE INDEX IF NOT EXISTS idx_beacon_warning_defender ON beacon_warning(server_id, defender_player_id, arrive_at);
COMMENT ON TABLE beacon_warning IS '烽火台预警：等级越高揭示越多来袭信息';
