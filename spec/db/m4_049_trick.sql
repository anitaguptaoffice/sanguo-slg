-- R3-S4: 招贤馆基础计谋：施法记录与空城计状态。
CREATE TABLE IF NOT EXISTS trick_cast (
    server_id       INT    NOT NULL,
    cast_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    player_id       BIGINT NOT NULL,
    city_id         BIGINT NOT NULL,
    trick_type      SMALLINT NOT NULL CHECK (trick_type >= 1 AND trick_type <= 4),
    target_march_id BIGINT NOT NULL DEFAULT 0,
    success         BOOLEAN NOT NULL,
    roll            INT    NOT NULL,
    chance          INT    NOT NULL,
    item_cfg_id     INT    NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (server_id, cast_id)
);

CREATE TABLE IF NOT EXISTS city_trick (
    server_id  INT    NOT NULL,
    city_id    BIGINT NOT NULL,
    trick_type SMALLINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (server_id, city_id, trick_type)
);
COMMENT ON TABLE city_trick IS '空城计等城池伪装状态';
