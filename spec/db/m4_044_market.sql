-- R2-S6: 同服玩家市场挂单与商队运输。
CREATE TABLE IF NOT EXISTS market_offer (
    server_id       INT    NOT NULL,
    offer_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    seller_player_id BIGINT NOT NULL,
    seller_city_id  BIGINT NOT NULL,
    resource_type   SMALLINT NOT NULL CHECK (resource_type >= 0 AND resource_type <= 3),
    amount          BIGINT NOT NULL CHECK (amount > 0),
    price_milli     BIGINT NOT NULL CHECK (price_milli > 0),
    gold_total      BIGINT NOT NULL CHECK (gold_total > 0),
    status          SMALLINT NOT NULL DEFAULT 0 CHECK (status >= 0 AND status <= 3),
    range_hours     SMALLINT NOT NULL DEFAULT 1 CHECK (range_hours >= 1 AND range_hours <= 24),
    buyer_player_id BIGINT,
    buyer_city_id   BIGINT,
    deliver_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (server_id, offer_id)
);
COMMENT ON TABLE market_offer IS '市场挂单：0=待售 1=商队运输中 2=已送达 3=已取消';
CREATE INDEX IF NOT EXISTS idx_market_offer_open
    ON market_offer(server_id, status, resource_type, created_at);
CREATE INDEX IF NOT EXISTS idx_market_offer_seller
    ON market_offer(server_id, seller_player_id, status);
CREATE INDEX IF NOT EXISTS idx_market_offer_buyer
    ON market_offer(server_id, buyer_player_id, status, deliver_at);
